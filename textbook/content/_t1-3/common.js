const avg = (a) => a.reduce((t, v) => t + v, 0) / a.length;
const sum = (a) => a.reduce((t, v) => t + v, 0);
// 연평균 기온·연 강수량·연교차 한 줄 요약
export const SUMMARY = (c) =>
  `연평균 ${avg(c.temp).toFixed(1)}℃ · 연교차 ${(Math.max(...c.temp) - Math.min(...c.temp)).toFixed(1)}℃ · 연 강수량 ${Math.round(sum(c.precip)).toLocaleString('en-US')}mm`;

// 기후 그래프 하나: label(왼쪽 위 이름), temp(월평균 기온 12개), precip(월 강수량 12개)
export const CL = (label, temp, precip, o = {}) => ({
  t: 'chart', kind: 'climate', compact: true, label, temp, precip,
  title: o.title, note: o.note, h: o.h ?? 190, w: o.w,
  tMin: o.tMin ?? -10, tMax: o.tMax ?? 30, tStep: o.tStep ?? 10, pMax: o.pMax ?? 300,
});

// 도시 이름으로 기후 그래프 만들기 (제목: 기후 이름, 그래프 안: 도시 이름, 아래: 요약)
export const CITYCL = (name, o = {}) => {
  const c = CITY[name];
  return CL(o.label ?? name, c.temp, c.precip, { title: o.title ?? `${c.k} 기후`, note: o.note ?? SUMMARY(c), ...o });
};

